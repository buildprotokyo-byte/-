def decoy_pairs() -> Iterator[Pair]:
    """囮の対を全部返す。"""
    for left, right in PART_SWAPS:
        yield Pair(left, right, False, "1 部位の入れ替え")
    for left, right in STATE_SWAPS:
        yield Pair(left, right, False, "2 状態の入れ替え")
    for left, right in CATEGORY_SWAPS:
        yield Pair(left, right, False, "3 科目の入れ替え", level="科目")
    for left, right in MATERIAL_SWAPS:
        yield Pair(left, right, False, "4 材料の入れ替え")
    for name, a, b, unit in QUANTITY_DECOYS:
        yield Pair(name, name, False, "5 数量違い", left_quantity=a, right_quantity=b, unit=unit)


def paraphrase_pairs() -> Iterator[Pair]:
    """正しい言い換えの対を全部返す。"""
    for left, right, level in PARAPHRASES:
        yield Pair(left, right, True, "言い換え", level=level)
