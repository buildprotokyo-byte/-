"""精度モード(精密/標準/概算)の定義。

自動積算には、精密な見積もりが必要な場合と、概算(大まかな金額感)で
よい場合がある。キラークエスチョンの「どこまで質問するか」を、依頼の
性質に応じて切り替えられるようにするための列挙型。挙動の詳細は
``killer_question/engine.py`` と ``docs/killer_question_precision_report.md``
を参照。
"""

from __future__ import annotations

from enum import Enum

#: 概算モードで打ち切る基準となる、累積確信度カバレッジの既定目標値。
#: 「確定済みの金額が全体の85%に達したら打ち切る」という初期値の提案どおり。
DEFAULT_TARGET_COVERAGE = 0.85


class PrecisionMode(Enum):
    """キラークエスチョンの継続方針。"""

    PRECISE = "precise"
    """精密: 依存関係による削減効果が無くなっても、原則すべての要素が
    解決するまで直接質問を続ける。軸品質ファイアウォールの階層2(仮採用)も、
    標本監査だけで済ませず、直接確認の対象に含める
    (``killer_question/firewall_bridge.py`` 参照)。"""

    STANDARD = "standard"
    """標準: 段階7までの既存の動作。依存関係による削減が見込めなくなった
    時点で打ち切る。階層2は標本監査のみで自動採用する(変更なし)。"""

    ROUGH = "rough"
    """概算: 金額インパクト(数量×単価)で重み付けしたスコアの大きい要素から
    優先的に質問し、累積確信度カバレッジ(確定済み金額 ÷ 見積もり全体の
    金額合計の推定値)が目標値に達した時点で、残りは質問せず打ち切る。
    価格情報が一切登録されていない場合は、カバレッジ判定ができないため
    標準モードと同じ停止条件にフォールバックする。"""
