"""実案件 P011 の設計図面に対する、人手で確定した参照データ。

**この参照データの作り方(再現手順)**

1. `設計図面_匿名化済み.pdf` を `axes.image_axis.pdf_pages.rasterize(dpi=200)` で
   ラスター化する。**この名前で呼べるファイルは 2 つある。ここで使ったのは
   v1(全ページを画像化した版・A0 相当・文字データ 0)のほうである。**
   54 周目に、箱の画素が収まる切り出し画像を持てるのがどちらかで確かめた
   (`docs/d_reference_provenance_report.md`)。
2. 8 ページ目(図面番号 意-6「改装平面図」)を取り出し、
   `PLAN_CROP` の矩形で図面本体を切り出す(表題欄と右側の仕上表を除く)。
3. 切り出した画像を 3x3 のタイルに分けて 1 枚ずつ目視し、**開き戸の円弧**を
   数え上げ、座標格子を重ねた画像から外接矩形を読み取る。

**この参照データの限界(正直に書く)**

- 箱の座標は目視読み取りなので、数ピクセル単位では正確でない。位置合わせの
  判定には IoU 0.10(段階Aでいう「実務寄り」の基準)を使うこと。
- 「開き戸の円弧」だけを数えている。この図面の新設建具 WD-1〜WD-4 は
  **引戸・折戸**で円弧を描かないため、参照データには入っていない
  (`SLIDING_DOOR_MARKERS` に別途記録した)。
- 34 ページ全体ではなく 8 ページ目だけの参照データである。
- **この参照データで `axes/image_axis/pdf_vector_symbols.py` を採点することはできない。**
  v1 にはベクターの図形が 1 ページにも無いので、同じ経路を当てると 0 件になる。
  ベクターの経路が拾っている 90 件は**匿名化 v2** のものであり、**別の紙である**
  (`docs/d_vector_path_on_reference_sheet_report.md`)。
"""

