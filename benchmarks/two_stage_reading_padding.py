def padded_pages(case: CaseSet) -> tuple[str, ...]:
    """概要ページの位置はそのままに、24ページへかさ増しした資料一式。"""
    filler = _stale_number_filler(case) + _common_filler(case.set_id, case.title)
    details = list(case.detail_pages)
    need = TARGET_PAGE_COUNT - len(case.overview_pages) - len(details)
    if len(filler) < need:  # pragma: no cover - 定義上起きない
        raise AssertionError(
            f"詰め物ページが足りない: 必要 {need} / 用意 {len(filler)}"
        )
    filler = filler[:need]

    # 概要ページの後ろに、詳細ページを等間隔で散らす。
    tail_len = need + len(details)
    step = tail_len / (len(details) + 1)
    slots = {int(round(step * (i + 1))) - 1 for i in range(len(details))}
    while len(slots) < len(details):  # pragma: no cover - 丸めの保険
        slots.add(max(slots) + 1)
    slots = sorted(slots)[: len(details)]

    tail: list[str] = []
    fi = di = 0
    for pos in range(tail_len):
        if pos in slots and di < len(details):
            tail.append(details[di])
            di += 1
        else:
            tail.append(filler[fi])
            fi += 1
    tail.extend(details[di:])
    return tuple(list(case.overview_pages) + tail)


def padded_detail_pages(case: CaseSet) -> tuple[str, ...]:
    """方式Bの段階2に渡すページ。概要ページだけを抜いた残り全部。"""
    return tuple(p for p in padded_pages(case) if p not in case.overview_pages)


def all_padded() -> dict[str, tuple[str, ...]]:
    return {case.set_id: padded_pages(case) for case in ALL_SETS}
