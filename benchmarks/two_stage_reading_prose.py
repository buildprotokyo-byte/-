def prose_overview_pages(case: CaseSet) -> tuple[str, ...]:
    return PROSE_OVERVIEW[case.set_id]


def prose_pages(case: CaseSet) -> tuple[str, ...]:
    """レベル2の資料の、概要ページだけを散文版に差し替えたもの。"""
    rest = [p for p in padded_pages(case) if p not in case.overview_pages]
    return tuple(list(prose_overview_pages(case)) + rest)


def prose_detail_pages(case: CaseSet) -> tuple[str, ...]:
    """方式Bの段階2に渡すページ。概要(散文)ページだけを抜いた残り。"""
    overview = set(prose_overview_pages(case))
    return tuple(p for p in prose_pages(case) if p not in overview)


def all_prose() -> dict[str, tuple[str, ...]]:
    return {case.set_id: prose_pages(case) for case in ALL_SETS}
