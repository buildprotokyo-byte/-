"""トライアル15 「2段階読み(概要確定→詳細)」検証用の合成資料一式。

すべて架空の物件で、実在する企業・個人の情報は含まない。

このモジュールは *資料の本文* と *正解値の算出根拠* の両方を持つ。
資料を読む側(方式A / 方式B の読み取り担当)には ``pages()`` が返す本文と
``QUESTIONS`` だけを渡し、``ground_truth()`` の値は一切渡さない。
採点は ``run_two_stage_reading_eval.py`` 側が凍結済みの正解値ファイル
(``two_stage_reading_key.json``)と突き合わせて行う。
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Callable


@dataclass(frozen=True)
class Question:
    """読み取り担当に出す設問ひとつ。"""

    qid: str
    text: str
    unit: str
    # この設問が何を試しているか。
    #   "scope"      … 工事対象範囲を概要から取らないと誤る
    #   "datum"      … 基準寸法(グリッド/スパン/符号表)を概要から取らないと誤る
    #   "condition"  … 現況を概要から取らないと誤る
    #   "extra_rule" … 概要ページにはあるが「基準寸法・範囲・現況」の
    #                  3要素には入らない計上ルールが要る
    trap: str


@dataclass(frozen=True)
class CaseSet:
    """資料1セット(概要ページ + 詳細ページ + 設問)。"""

    set_id: str
    title: str
    overview_pages: tuple[str, ...]
    detail_pages: tuple[str, ...]
    questions: tuple[Question, ...]
    answers: dict[str, float]
    # 詳細ページに置いた「概要を見ないと誤読する」おとりの数値。
    decoys: dict[str, float] = field(default_factory=dict)


def _m2_per_grid(mm: float) -> float:
    return (mm / 1000.0) ** 2


