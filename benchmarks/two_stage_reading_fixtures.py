def ground_truth() -> dict[str, float]:
    """設問IDから正解値への辞書。採点側だけが使う。"""
    out: dict[str, float] = {}
    for case in ALL_SETS:
        for question in case.questions:
            out[question.qid] = round(case.answers[question.qid], 4)
    return out


def question_traps() -> dict[str, str]:
    return {q.qid: q.trap for case in ALL_SETS for q in case.questions}


def format_questions(case: CaseSet) -> str:
    lines = []
    for question in case.questions:
        lines.append(f"  {question.qid}: {question.text} は何 {question.unit} か。")
    return "\n".join(lines)


def get_set(set_id: str) -> CaseSet:
    for case in ALL_SETS:
        if case.set_id == set_id:
            return case
    raise KeyError(set_id)
